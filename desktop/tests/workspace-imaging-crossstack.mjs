// Generated fixtures only: actual bridge descriptors -> host assets -> viewer.
import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {createRequire} from 'node:module';
import {hydrateCase} from '../src/case-data.ts';
import {hydrateDisplaySeries,workspaceDisplay} from '../src/workspace-imaging-data.ts';
const require=createRequire(import.meta.url);
const {AssetRegistry}=require('../electron/assets.cjs');
const fixture=JSON.parse(await readFile(process.argv[2],'utf8'));
const assets=new AssetRegistry(fixture.transferRoot);
const primary=await assets.expose(fixture.primary);
const attached=await assets.expose(fixture.attached);
assert.equal('path' in attached.volume.mri,false);
const api={readAsset:id=>assets.read(id)};
const primaryView=await hydrateCase(primary,api);
const view=await hydrateDisplaySeries(primary,attached,api);
assert.deepEqual(Array.from(view.volume.mri),fixture.expectedImage);
assert.equal(view.volume.compartments.length,1);
assert.equal(view.volume.compartments[0].name,'source_label_1');
assert.equal(view.descriptor.annotationKind,'source-provided');
assert.equal(view.volume.affine[0][3],100);
assert.equal(primaryView.affine[0][3],0);
assert.equal(view.volume.planningHash,undefined);
assert.equal(primaryView.compartments.length,0);
const selected=workspaceDisplay(primaryView,view);
assert.equal(selected.primaryOverlaysPermitted,false);
assert.equal(selected.planningInteractionPermitted,false);
assert.equal(workspaceDisplay(primaryView,null).caseData,primaryView);
await assert.rejects(hydrateDisplaySeries({...primary,caseHash:'sha256:'+'f'.repeat(64)},attached,api));
process.stdout.write('Bridge -> AssetRegistry -> hydrateCase -> native-frame selection passed\n');
