import importlib.util
import json
from pathlib import Path

import numpy as np
import pytest

PATH = Path(__file__).resolve().parents[1]/"scripts/poc_ixi265_vessel_agreement.py"
SPEC = importlib.util.spec_from_file_location("vessel_agreement", PATH)
m = importlib.util.module_from_spec(SPEC)
SPEC.loader.exec_module(m)


def test_fixed_domain_and_unlabelled_semantics():
    p=np.array([1,1,0,1],bool); r=np.array([1,0,1,1],bool); c=np.array([1,1,1,0],bool)
    result=m.set_counts(p,r,c,2.)
    assert result["intersection_voxels"] == 1
    assert result["positive_mask_dice"] == .5
    assert result["positive_mask_jaccard"] == 1/3
    assert result["provided_positive_reference_coverage_fraction"] == .5
    assert result["prediction_in_UNLABELLED_reference_voxels"] == 1
    assert result["reference_voxels_excluded_by_sampling_domain"] == 1
    assert result["physical_volumes_mm3"]["intersection"] == 2
    assert "false_positive" not in json.dumps(result)


def test_empty_sets_do_not_fabricate_agreement():
    empty=np.zeros(4,bool); domain=np.ones(4,bool)
    result=m.set_counts(empty,empty,domain,1.)
    assert result["positive_mask_dice"] is None
    assert result["positive_mask_jaccard"] is None
    assert result["provided_positive_reference_coverage_fraction"] is None
    result=m.set_counts(domain,empty,domain,1.)
    assert result["positive_mask_dice"] == 0
    assert result["provided_positive_reference_coverage_fraction"] is None


def test_fixed_threshold_is_strict_and_rejects_change():
    scores=np.array([0.,.5,.5001,1.])
    m.verify_threshold(np.array([0,0,1,1],bool),scores)
    with pytest.raises(ValueError,match="score>0.5"):
        m.verify_threshold(np.array([0,1,1,1],bool),scores)
    with pytest.raises(ValueError,match="Invalid"):
        m.verify_threshold(np.zeros(1,bool),np.array([np.nan]))


def test_physical_grid_error_rejects_axis_flip():
    affine=np.eye(4); changed=affine.copy(); changed[0,0]=-1
    assert m.corner_error([3,4,5],affine,affine) == 0
    assert m.corner_error([3,4,5],affine,changed) == 4


def test_component_connectivity_no_pruning_or_mutation():
    mask=np.zeros((5,5,5),bool); mask[1,1,1]=True; mask[2,2,2]=True; mask[4,0,0]=True
    before=mask.copy(); result=m.component_boundary_summary(mask,np.ones_like(mask))
    assert result["connected_components"] == 2
    assert result["largest_component_voxels"] == 2
    assert result["boundary_voxels"] == 3
    assert result["foreground_on_sampling_domain_boundary_voxels"] == 1
    assert np.array_equal(mask,before)


def test_metadata_preparation_does_not_touch_payload(monkeypatch):
    original=m.sha
    allowed={m.ROOT/p for p in m.METADATA} | {PATH,Path(__file__).resolve()}
    def guarded_sha(path):
        assert Path(path) in allowed
        return original(path)
    monkeypatch.setattr(m,"sha",guarded_sha)
    protocol=m.prepare()
    assert protocol["role"] == "TRAIN" and protocol["training_admitted"] is False
    assert protocol["source_reference_used_in_inference"] is False
    assert protocol["independent_accuracy_claim"] is False


def test_wrong_payload_hash_rejected_before_decode(tmp_path,monkeypatch):
    import nibabel as nib
    file=tmp_path/"wrong.bin"; file.write_bytes(b"tiny generated bytes")
    protocol={"inputs":{"reference":{"path":str(file),"sha256":"0"*64}}}
    protocol_path=tmp_path/"protocol.json"; protocol_path.write_text(json.dumps(protocol))
    monkeypatch.setattr(m,"PROTOCOL",protocol_path)
    monkeypatch.setattr(m,"prepare",lambda:protocol)
    monkeypatch.setattr(nib,"load",lambda *a,**k:pytest.fail("Decode occurred before binding"))
    with pytest.raises(ValueError,match="Frozen image bytes changed"):
        m.execute()
