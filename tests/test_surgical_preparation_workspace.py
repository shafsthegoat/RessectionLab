def reseal(value, key):
    value[key] = semantic_digest({k: v for k, v in value.items() if k != key})
    return value


def source_record(engine):
    return {'branches': {'main': engine.snapshot()}, 'branchId': 'main',
        'position': len(engine.actions), 'parents': {'main': None},
        'timeline': {'main': copy.deepcopy(engine.history)}}


