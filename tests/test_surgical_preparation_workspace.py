def test_generation_cancellation_transaction_after_real_preparation_is_atomic(study, monkeypatch):
    """Cancel downstream, after real physical preparation and task binding."""
    engine, native, controls, _, _ = study
    before = engine.snapshot(); files = hashes(native); calls = []
    class Cancelled(RuntimeError): pass
    def downstream(prepared, *args, **kwargs):
        calls.append(1)
        assert prepared.state['removed'] and not engine.state['removed']
        assert admission.validate_admission(prepared, admission.admission(prepared))
        raise Cancelled('downstream request cancelled')
    monkeypatch.setattr(planning.two_tool, 'generate_comparison', downstream)
    with pytest.raises(Cancelled): planning.generate(engine, controls, native.root)
    assert calls == [1] and engine.snapshot() == before and hashes(native) == files


def test_final_report_install_cancellation_transaction_is_atomic(study, monkeypatch):
    """Cancel after the real configured restore, before publishing the study."""
    engine, _, _, report, case = study
    record = source_record(engine); before = copy.deepcopy(record); restored = []
    restore = SurgicalEngine.restore
    class Cancelled(RuntimeError): pass
    def injected(*args, **kwargs):
        result = restore(*args, **kwargs); restored.append(1); return result
    def check():
        if restored: raise Cancelled('after configured native restore')
    monkeypatch.setattr(SurgicalEngine, 'restore', injected)
    with pytest.raises(Cancelled):
        workspace.install_report(engine, record, case.semantic_hash, report, check=check)
    assert restored == [1] and record == before


def test_final_application_cancellation_transaction_is_atomic(installed, monkeypatch):
    """Inject only at the transaction boundary after real report validation."""
    source, _, record, item, _, case = installed
    record.update(branchId='main', position=len(source.actions)); before = copy.deepcopy(record)
    materialize = planning.materialize
    class Cancelled(RuntimeError): pass
    cancelled = []
    def injected(*args, **kwargs):
        value = materialize(*args, **kwargs); cancelled.append(True); return value
    def check():
        if cancelled: raise Cancelled('after native materialization')
    monkeypatch.setattr(planning, 'materialize', injected)
    with pytest.raises(Cancelled):
        workspace.install_application(source, record, case.semantic_hash, item, 'width-0', 'prepared', check=check)
    assert cancelled and record == before


