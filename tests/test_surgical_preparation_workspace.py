def test_real_preparation_retains_setup_source_cost_and_stop(study):
    engine, _, _, report, _ = study
    configured = report['configuredSnapshot']; row = report['rows'][0]
    assert configured['actions'][:-1] == engine.actions
    assert configured['actions'][-1]['operation'] == 'configure'
    assert configured['actions'][-1]['mechanicsRevision'] == 2
    assert configured['actions'][-1]['clockRevision'] == 1
    proof = row['preparation']; public = proof['publicPlan']
    chosen = public['attempts'][public['decision']['selectedIndex']]
    assert proof['nativeReplayVerified'] and chosen['complete']
    assert chosen['summary']['additionalTargetMm3'] == 0.
    assert chosen['summary']['additionalNonTargetMm3'] > 0.
    assert row['preparedSnapshot']['actions'][:len(configured['actions'])] == configured['actions']
    assert row['preparedAdmission']['baseline']['position'] == len(row['preparedSnapshot']['actions'])
    assert report['baselineBurden'] == {'targetRemovedMm3': 0., 'nonTargetRemovedMm3': 0., 'elapsedSeconds': 0.}
    prepared, receipt = planning.materialize(engine, report, 'width-0', 'prepared')
    assert prepared.snapshot() == row['preparedSnapshot']
    assert receipt['preparationActions'] > 0 and receipt['suffixActions'] == 0
    assert receipt['nativeMatchesPublicPrediction'] and receipt['withdrawalComplete']
    # This narrow generated corridor has a legitimate downstream STOP. Its
    # healthy-tissue preparation remains selectable, never a complete plan.
    assert row['comparison']['publicPlan']['decision']['selectedId'] == 'stop'
    assert report['policies']['completePlanAware'] == {'selectedPreparationId': None, 'suffixId': 'stop'}
    with pytest.raises(ValueError, match='complete progress-qualified'):
        planning.materialize(engine, report, 'width-0', 'withdraw')


@pytest.mark.parametrize('change', ['schema', 'extra', 'source', 'configured', 'row-id',
    'row-count', 'width', 'admission', 'physical-cost', 'public-choice', 'policy', 'incomplete'])
def test_resealed_reports_do_not_grant_producer_authority(study, change):
    engine, _, _, original, _ = study
    report = copy.deepcopy(original); row = report['rows'][0]
    if change == 'schema': report['schema'] += '-forged'
    elif change == 'extra': report['privateEvaluatorScore'] = 1.
    elif change == 'source': report['sourceSnapshotHash'] = '0'*64
    elif change == 'configured': report['configuredSnapshot'] = engine.snapshot()
    elif change == 'row-id': row['id'] = 'forged'
    elif change == 'row-count': report['rows'].append(copy.deepcopy(row))
    elif change == 'width': row['widthMm'] = 1.
    elif change == 'admission':
        row['preparedAdmission']['task']['entry']['radiusMm'] += .1
        reseal(row['preparedAdmission'], 'admissionSeal')
    elif change == 'physical-cost':
        row['preparation']['publicPlan']['attempts'][0]['summary']['additionalNonTargetMm3'] = 0.
        reseal(row['preparation']['publicPlan'], 'publicSeal')
    elif change == 'public-choice':
        row['comparison']['publicPlan']['decision']['selectedId'] = 'long'
        reseal(row['comparison']['publicPlan'], 'publicPlanSeal')
        reseal(row['comparison'], 'reportSeal')
    elif change == 'policy': report['policies']['completePlanAware']['selectedPreparationId'] = 'width-0'
    else: report['incompleteRows'] = ['width-0']
    reseal(report, 'reportSeal')
    with pytest.raises(ValueError): planning.validate_report(engine, report)
    assert semantic_digest(engine.snapshot()) == original['sourceSnapshotHash']


