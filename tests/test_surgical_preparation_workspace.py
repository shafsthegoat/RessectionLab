def test_native_bridge_preview_install_multiple_studies_save_reopen(study, tmp_path):
    from resectionlab.desktop_bridge import BridgeSession, _Request
    from resectionlab.imaging import save_case, read_case_artifacts
    engine, native, controls, _, case = study
    record = read_case_artifacts(native.root.parent/'scene/patient.ressectionlab')['surgical_toolbox']
    record.update(source_record(engine))
    path = tmp_path/'preparation.ressectionlab'
    save_case(case, path, artifacts={'surgical_toolbox': record})
    session = BridgeSession(tmp_path/'transfers')
    progress_events=[]
    def progress(fraction, message, *details):
        assert type(fraction) in (int,float) and 0<=fraction<=1 and type(message) is str
        progress_events.append((fraction,message))
    def call(command, state=None, **values):
        return session.execute('surgicalRehearsal', {'caseHash': case.semantic_hash, 'command': command,
            **({'expectedStateId': state} if state is not None else {}), **values}, _Request(command), progress)
    try:
        session.execute('loadCase', {'path': str(path)}, _Request('load'), lambda *_: None)
        initial = call('inspect'); start = initial['view']['stateId']
        before = copy.deepcopy(session.surgical_sessions[case.semantic_hash][2]); data = path.read_bytes()
        assert initial['preparationPlanningAvailability']['available']
        suggestion = call('suggestPreparation', start, acknowledgeResearchUnknowns=True)
        assert suggestion['changed'] is False and suggestion['view']['stateId'] == start
        assert suggestion['preparationSuggestion']['sourceSceneId'] == engine.scene.identity
        assert session.surgical_sessions[case.semantic_hash][2] == before and path.read_bytes() == data
        generated = call('generatePreparations', start, constraints=controls, acknowledgeResearchUnknowns=True)
        assert progress_events and progress_events[0][0]==0.
        report = generated['preparationPlanning']
        assert generated['view']['stateId'] == start and generated['position'] == 0
        data = path.read_bytes(); before = copy.deepcopy(session.surgical_sessions[case.semantic_hash][2])
        preview = call('previewPreparation', start, candidateId='width-0', phase='prepared', expectedPlanSeal=report['reportSeal'])
        assert preview['changed'] is False and preview['view']['stateId'] == start
        assert preview['approachPreview']['kind'] == 'preparation' and preview['approachPreview']['phaseId'] == 'prepared'
        assert preview['approachPreview']['view']['stateId'] != start
        assert session.surgical_sessions[case.semantic_hash][2] == before and path.read_bytes() == data
        installed = call('applyPreparation', start, candidateId='width-0', phase='prepared', expectedPlanSeal=report['reportSeal'])
        first_branch = installed['branchId']; endpoint = installed['view']['stateId']
        first_admission = admission.admission(session.surgical_sessions[case.semantic_hash][1])
        assert installed['changed'] and endpoint != start and installed['preparationPlanning']['current'] is False
        source = call('selectBranch', endpoint, branchId='main', position=0)
        assert source['view']['stateId'] == start
        assert not hasattr(session.surgical_sessions[case.semantic_hash][1], '_planning_task_admission')
        second_controls = copy.deepcopy(controls); second_controls['target']['radiusMm'] = 5.
        second = call('generatePreparations', start, constraints=second_controls, acknowledgeResearchUnknowns=True)
        second_install = call('applyPreparation', start, candidateId='width-0', phase='prepared',
            expectedPlanSeal=second['preparationPlanning']['reportSeal'])
        assert second_install['branchId'] != first_branch
        second_admission = admission.admission(session.surgical_sessions[case.semantic_hash][1])
        assert first_admission != second_admission
        first_again = call('selectBranch', second_install['view']['stateId'], branchId=first_branch,
            position=len(report['rows'][0]['preparedSnapshot']['actions']))
        assert first_again['view']['stateId'] == endpoint
        assert admission.admission(session.surgical_sessions[case.semantic_hash][1]) == first_admission
        saved = tmp_path/'saved.ressectionlab'
        session.execute('saveCase', {'caseHash': case.semantic_hash, 'path': str(saved)}, _Request('save'), lambda *_: None)
        archived = read_case_artifacts(saved)['surgical_toolbox']
        assert len(archived['preparationComparisons']) == len(archived['preparationApplications']) == 2
        assert 'taskAdmission' not in archived and archived['branchId'] == first_branch
        assert archived['preparationComparisons'][0]['report']['reportSeal'] == report['reportSeal']
    finally:
        session.close()
    fresh = BridgeSession(tmp_path/'reopened-transfers')
    try:
        fresh.execute('loadCase', {'path': str(saved)}, _Request('load'), lambda *_: None)
        reopened = fresh.execute('surgicalRehearsal', {'caseHash': case.semantic_hash, 'command': 'inspect'},
            _Request('reopen'), lambda *_: None)
        assert reopened['branchId'] == first_branch and reopened['view']['stateId'] == endpoint
        assert reopened['preparationPlanning']['revision'] == 2
        assert admission.admission(fresh.surgical_sessions[case.semantic_hash][1]) == first_admission
    finally:
        fresh.close()
