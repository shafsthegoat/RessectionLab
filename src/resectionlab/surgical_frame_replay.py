"""Read-only playback of successful shared-engine microstep observations.

Frames are compressed disposable cache data. They are generated by the public
step operation from an admitted action boundary, and the finalized endpoint is
checked against independently replayed history before any frame is returned.
No interpolation, effects inversion, or editable intermediate state is used.
"""
from __future__ import annotations
from collections import OrderedDict
import copy
import json
import sys
import zlib
from .surgical_engine import SurgicalEngine
from .core import semantic_digest
from .core import thaw_json
from .surgical_replay_cache import SurgicalReplayCache, _owned_bytes
from .surgical_observed_cache import (FrameAdmission, ObservedFrameStore, receipt_hash, ImplementationChanged)
from .surgical_flow_display import FlowDisplayTrace, validate_flow_display, trim_frame_flows


class ObservedFrameCollector:
    """Transactional observer shared by candidate clones, outside engine state.

    Only finalized public outcomes matching the immutable canonical admission
    publish. Rejected candidates and failed microsteps leave no readable cache.
    Cache I/O/budget failures do not change the public operation's outcome.
    """
    def __init__(self, cache, admission):
        self.cache, self.admission = cache, admission
        self.writer = None; self.position = None; self.matches = False
        self.last_effective_activation = None
        self.flow = None

    def abort(self):
        if self.writer is not None: self.writer.abort()
        if self.flow is not None: self.flow.close()
        self.flow = None
        self.writer = None; self.position = None; self.matches = False
        self.last_effective_activation = None

    @staticmethod
    def _activation(engine, acting=None, active=None):
        return {key: bool(active if key == acting else slot['active'])
                for key, slot in engine.state['slots'].items()}

    def _capture(self, engine, kind, activation):
        if self.writer is None: return
        try: self.writer.capture(engine, kind, activation)
        except (OSError, ValueError, TypeError):
            self.writer.abort(); self.writer = None
            if self.flow is not None: self.flow.close()

    def begin(self, engine, action):
        self.abort(); self.admission.check(engine)
        self.position = len(engine.actions)
        if not 0 <= self.position <= len(self.admission.history):
            raise ValueError('Observed collector action position differs')
        if engine.state_id != self.admission.boundary_id(self.position):
            raise ValueError('Observed collector initial state differs from canonical admission')
        self.matches = (self.position < len(self.admission.history)
                        and semantic_digest(action) == self.admission.action_hashes[self.position])
        self.next_time = float(engine.state['elapsedSeconds']) + .2
        if self.matches:
            try: self.writer = self.cache.store.begin(self.admission, self.position)
            except (OSError, ValueError): self.writer = None
            if self.writer is not None:
                self.flow = FlowDisplayTrace(engine.scene.identity, self.position, engine.state['elapsedSeconds'], engine.scene.shape)
                engine._flow_display_trace = self.flow
            self._capture(engine, 'action_start', self._activation(engine))

    def observe(self, engine, acting_slot, effective_active):
        if self.position is None: return
        if self.flow is not None: self.flow.commit_substep(engine.state['elapsedSeconds'])
        # Successful public microstep observation, even when shorter than the
        # display cadence. The finalized state retains its own latched switch.
        self.last_effective_activation = self._activation(engine, acting_slot, effective_active)
        if self.writer is None: return
        if engine.state['elapsedSeconds'] + 1e-10 >= self.next_time:
            self._capture(engine, 'microstep', self.last_effective_activation)
            while self.next_time <= engine.state['elapsedSeconds'] + 1e-10:
                self.next_time += .2

    def end(self, engine, action, outcome):
        if outcome.get('status') == 'rejected':
            self.abort(); return
        position = self.position
        if (position is None or not self.matches or len(engine.actions) != position + 1
                or semantic_digest(action) != self.admission.action_hashes[position]
                or engine.state_id != self.admission.boundary_id(position + 1)
                or receipt_hash(outcome) != self.admission.receipt_hashes[position]):
            self.abort()
            raise ValueError('Observed action outcome differs from canonical admission')
        self._capture(engine, 'action_boundary', self.last_effective_activation or self._activation(engine))
        if self.writer is not None:
            try: self.writer.publish(engine, outcome)
            except (OSError, ValueError, TypeError): self.writer.abort()
        self.abort()


class _ObservedFrames(SurgicalEngine):
    def clone(self):
        other = super().clone()
        other._frames = self._frames[:]
        return other

    def _capture(self, kind, activation):
        trace = getattr(self, '_flow_display_trace', None)
        if trace is None or not trace.active:
            trace = self._flow_display_trace = FlowDisplayTrace(
                self.scene.identity, len(self.actions), self.state['elapsedSeconds'], self.scene.shape)
        state_id = self.state_id
        self._frames.append({'observedTimeSeconds': float(self.state['elapsedSeconds']), 'kind': kind,
            'effectiveActivation': activation, 'stateId': state_id,
            'flowDisplay': trace.capture(state_id, self.state['elapsedSeconds']),
            'state': zlib.compress(json.dumps(self.state, separators=(',', ':'), allow_nan=False).encode(), 1)})
        # Optional indicators may not turn a state-only fallback into a budget
        # failure. Even the empty envelope is optional at zero spare headroom.
        self._flow_capture_bytes = getattr(self, '_flow_capture_bytes', 0) + _owned_bytes(self._frames[-1])
        limit = getattr(self, '_frame_max_bytes', 64 * 1024**2)
        if self._flow_capture_bytes > limit:
            trim_frame_flows(self._frames)
            self._flow_capture_bytes = _owned_bytes(self._frames)
        if self._flow_capture_bytes > limit:
            trim_frame_flows(self._frames, omit=True)
            self._flow_capture_bytes = _owned_bytes(self._frames)

    def _substep(self, key, op, p, q, active, dt):
        events = super()._substep(key, op, p, q, active, dt)
        self._last_effective_activation = {hand: bool(active if hand == key else slot['active'])
                                           for hand, slot in self.state['slots'].items()}
        collector = getattr(self, '_frame_collector', None)
        if collector is not None:
            collector.observe(self, key, active)
            return events
        trace = getattr(self, '_flow_display_trace', None)
        if trace is not None: trace.commit_substep(self.state['elapsedSeconds'])
        if self.state['elapsedSeconds'] + 1e-10 >= self._next_frame_time:
            self._capture('microstep', self._last_effective_activation)
            while self._next_frame_time <= self.state['elapsedSeconds'] + 1e-10:
                self._next_frame_time += .2
        return events


class SurgicalFrameCache:
    def __init__(self, max_bytes=64 * 1024**2, *, directory=None, max_disk_bytes=None):
        if type(max_bytes) is not int or not 1 <= max_bytes <= 64 * 1024**2:
            raise ValueError('Observed frame RAM budget must be 1..64 MiB')
        self.max_bytes = max_bytes
        self._actions = OrderedDict()
        self.store = ObservedFrameStore(directory, max_disk_bytes=max_disk_bytes)

    def admit(self, current, snapshot, replay_cache, *, verified_history=None, check=lambda:None):
        """Once per private bridge generation, detach and freeze canonical data."""
        endpoint, history = replay_cache.seek(current, snapshot, len(snapshot['actions']), check=check, include_history=True)
        if verified_history is not None and semantic_digest(verified_history) != semantic_digest(history):
            raise ValueError('Frame admission history differs from canonical replay')
        check()
        return FrameAdmission.canonical(endpoint, snapshot, history)

    def collector(self, admission):
        return ObservedFrameCollector(self, admission)

    def _persistent_result(self, admission, item, index, *, display_only):
        result = admission.shell.clone()
        result.state = self.store.state(item, index)
        result._occupancy_cache = None
        frame = item['frames'][index]
        if result.state_id != frame['stateId']:
            raise ValueError('Observed frame state authentication differs')
        count = item['position'] + int(index == len(item['frames']) - 1)
        if display_only:
            # These recursively frozen prefixes are private, read-only display
            # ancestry. Editable boundaries always take the detached path.
            result.actions = admission.snapshot['actions'][:count]
            result.history = admission.history[:count]
            history = admission.history
        else:
            result.actions = thaw_json(admission.snapshot['actions'][:count])
            result.history = thaw_json(admission.history[:count])
            history = thaw_json(admission.history)
        return result, history

    @staticmethod
    def _playback(item, index):
        frames = item['frames']; frame = frames[index]
        manifest = [{k:v for k,v in row.items() if k not in ('state', 'fields', 'stateId', 'flowDisplay')} | {'frameIndex':i} for i,row in enumerate(frames)]
        start = frames[0]['observedTimeSeconds']
        return {'readOnly': True, 'position': item['position'], 'actionIndex': item['position'],
            'frameIndex': index, 'frameCount': len(frames), 'frames': manifest,
            'observedTimeSeconds': frame['observedTimeSeconds'],
            'actionElapsedSeconds': frame['observedTimeSeconds'] - start,
            'actionDurationSeconds': frames[-1]['observedTimeSeconds'] - start,
            'isActionBoundary': index in (0, len(frames)-1),
            'frameStateId': frame['stateId'],
            'fieldTokens': {name: blob['sha256'] for name, blob in
                frame.get('fields', {}).get('fields', {}).items() if name == 'flapComponents'},
            'effectiveActivation': dict(frame['effectiveActivation']),
            **({'flowDisplay': copy.deepcopy(frame['flowDisplay'])} if 'flowDisplay' in frame else {})}

    def _seek_admitted(self, current, admission, position, index, replay_cache, check, display_only):
        admission.check(current, admission.snapshot, admission.history)
        if type(position) is not int or not 0 <= position < len(admission.history) or type(index) is not int or index < 0:
            raise ValueError('Playback frame is unavailable')
        item = self.store.load(admission, position)
        if item is not None:
            item['position'] = position
            if index >= len(item['frames']): raise ValueError('Playback frame is unavailable')
            try:
                result, history = self._persistent_result(admission, item, index, display_only=display_only)
                check()
                return result, history, self._playback(item, index)
            except (OSError, ValueError, TypeError, KeyError, EOFError):
                item = None
        if item is None:
            # Derive exactly one missing action through public step; receipt
            # comparison precedes publication. Cold portable archives retain
            # the existing observed replay fallback when caching is unavailable.
            snapshot = thaw_json(admission.snapshot)
            baseline, _ = replay_cache.seek(current, snapshot, position, check=check, include_history=True)
            observed = _ObservedFrames(baseline.scene, protection=baseline.protection, guard_config=baseline.guard_config)
            observed.__dict__.update(baseline.clone().__dict__)
            observed._frames = []
            observed._frame_max_bytes = self.max_bytes
            observed._last_effective_activation = None
            collector = self.collector(admission)
            observed._frame_collector = collector
            action = thaw_json(admission.snapshot['actions'][position])
            try:
                collector.begin(observed, action)
                outcome = observed.step(action, check=check)
                collector.end(observed, action, outcome)
            except BaseException:
                collector.abort(); raise
            item = self.store.load(admission, position)
            if item is not None:
                item['position'] = position
                if index >= len(item['frames']): raise ValueError('Playback frame is unavailable')
                try:
                    result, history = self._persistent_result(admission, item, index, display_only=display_only)
                    return result, history, self._playback(item, index)
                except (OSError, ValueError, TypeError, KeyError, EOFError): pass
            return self.seek(current, snapshot, position, index, replay_cache, check=check,
                verified_history=thaw_json(admission.history))

    def _key(self, snapshot, position):
        return semantic_digest({'snapshot': snapshot, 'position': position})

    @property
    def statistics(self):
        return {'actions': len(self._actions), 'ownedBytes': self._bytes(),
                'maxBytes': self.max_bytes,
                'memoryMeaning': 'Compressed observed states, empty engine shells and canonical action receipts; shared source anatomy/geometry excluded. No branch actions or history retained.'}

    def _bytes(self):
        return sys.getsizeof(self._actions) + sum(item['bytes'] for item in self._actions.values())

    @staticmethod
    def _ancestry(snapshot, history):
        if not isinstance(history, list) or len(history) != len(snapshot['actions']):
            raise ValueError('Playback history length differs from canonical admission')
        previous = None
        for index, row in enumerate(history):
            if (row.get('action') != snapshot['actions'][index]
                    or row.get('status') not in ('accepted', 'partial')
                    or previous is not None and row.get('stateBefore') != previous):
                raise ValueError('Playback action ancestry differs from canonical admission')
            previous = row.get('stateAfter')
        if history and previous != snapshot['stateId']:
            raise ValueError('Playback archive endpoint differs from canonical admission')

    @staticmethod
    def _history(snapshot, receipt, history):
        # This keyword is private bridge data, never an IPC argument. Its
        # digest must still match the timeline returned by canonical admission
        # when the action's finalized endpoint was independently checked.
        if (not isinstance(history, list) or len(history) != len(snapshot['actions'])
                or semantic_digest(history) != receipt['historyHash']):
            raise ValueError('Playback history differs from canonical admission')
        return history

    @staticmethod
    def _result(item, snapshot, frame_index, history):
        result = item['shell'].clone()
        result.state = json.loads(zlib.decompress(item['frames'][frame_index]['state']))
        result._occupancy_cache = None
        final = frame_index == len(item['frames']) - 1
        position = item['receipt']['position'] + int(final)
        result.actions = copy.deepcopy(snapshot['actions'][:position])
        result.history = copy.deepcopy(history[:position])
        if final and result.state_id != item['receipt']['stateAfter']:
            raise ValueError('Playback boundary identity differs')
        if frame_index == 0 and result.state_id != item['receipt']['stateBefore']:
            raise ValueError('Playback initial identity differs')
        return result

    def boundary(self, snapshot, position, *, verified_history=None, admission=None):
        if admission is not None:
            try: admission.check(snapshot=snapshot, history=verified_history)
            except ImplementationChanged: return None
            if position == 0: return None
            item = self.store.load(admission, position - 1)
            if item is None: return None
            item['position'] = position - 1
            try: return self._persistent_result(admission, item, len(item['frames']) - 1, display_only=False)
            except (OSError, ValueError, TypeError, KeyError, EOFError): return None
        if position == 0: return None
        item = self._actions.get(self._key(snapshot, position - 1))
        if item is None or verified_history is None: return None
        item['shell'].scene.require_cache_source()
        history = self._history(snapshot, item['receipt'], verified_history)
        self._actions.move_to_end(self._key(snapshot, position - 1))
        return self._result(item, snapshot, len(item['frames']) - 1, history), copy.deepcopy(history)

    def seek(self, current, snapshot, position, frame_index, replay_cache, *, check=lambda:None, verified_history=None, admission=None, display_only=False):
        if admission is not None:
            try: admission.check(current, snapshot, verified_history)
            except ImplementationChanged:
                return self.seek(current, thaw_json(snapshot), position, frame_index, replay_cache,
                    check=check, verified_history=thaw_json(verified_history))
            return self._seek_admitted(current, admission, position, frame_index, replay_cache, check, display_only)
        if type(position) is not int or not 0 <= position < len(snapshot['actions']):
            raise ValueError('Playback action is unavailable')
        if type(frame_index) is not int or frame_index < 0:
            raise ValueError('Playback frame is unavailable')
        check()
        current.scene.require_cache_source()
        if current.scene.identity != snapshot.get('sceneId'):
            raise ValueError('Playback source differs from saved scene')
        key = self._key(snapshot, position)
        item = self._actions.get(key)
        if item is None:
            baseline, history = replay_cache.seek(current, snapshot, position, check=check, include_history=True)
            self._ancestry(snapshot, history)
            if history[position]['stateBefore'] != baseline.state_id:
                raise ValueError('Playback action ancestry differs from canonical admission')
            observed = _ObservedFrames(baseline.scene, protection=baseline.protection, guard_config=baseline.guard_config)
            observed.__dict__.update(baseline.clone().__dict__)
            observed._frames = []
            observed._frame_max_bytes = self.max_bytes
            observed._last_effective_activation = None
            observed._next_frame_time = baseline.state['elapsedSeconds'] + .2
            observed._capture('action_start', {hand:bool(slot['active']) for hand,slot in baseline.state['slots'].items()})
            outcome = observed.step(snapshot['actions'][position], check=check)
            if outcome['status'] == 'rejected' or observed.state_id != history[position]['stateAfter']:
                raise ValueError('Observed microstep endpoint differs from verified replay')
            receipt_fields = ('status', 'reason', 'reasonCode', 'completedFraction', 'events', 'deltas')
            if any(outcome.get(field) != history[position].get(field) for field in receipt_fields):
                raise ValueError('Observed action outcome differs from verified replay')
            observed._capture('action_boundary', getattr(observed, '_last_effective_activation', None)
                              or {hand:bool(slot['active']) for hand,slot in observed.state['slots'].items()})
            receipt = {'position': position, 'stateBefore': baseline.state_id,
                       'stateAfter': observed.state_id, 'historyHash': semantic_digest(history),
                       'actionHash': semantic_digest(snapshot['actions'][position])}
            item = {'frames': observed._frames, 'shell': SurgicalReplayCache._shell(baseline), 'receipt': receipt}
            def charge():
                item['bytes'] = _owned_bytes((item['frames'], item['receipt'], item['shell'].state,
                    item['shell'].actions, item['shell'].history)) + sum(map(sys.getsizeof,
                    (key, item, item['shell'], item['shell'].__dict__)))
            charge()
            if item['bytes'] > self.max_bytes:
                trim_frame_flows(item['frames']); charge()
            if item['bytes'] > self.max_bytes:
                trim_frame_flows(item['frames'], omit=True); charge()
            self._actions[key] = item
            # Bound compressed state bytes; account for retained endpoints too.
            while len(self._actions) > 1 and self._bytes() > self.max_bytes:
                self._actions.popitem(last=False)
            if self._bytes() > self.max_bytes:
                self._actions.pop(key, None)
        else:
            item['shell'].scene.require_cache_source()
            self._actions.move_to_end(key)
            if verified_history is None:
                _, history = replay_cache.seek(current, snapshot, position, check=check, include_history=True)
            else:
                history = verified_history
        if verified_history is not None:
            history = self._history(snapshot, item['receipt'], verified_history)
        else:
            history = self._history(snapshot, item['receipt'], history)
        frames = item['frames']
        if frame_index >= len(frames): raise ValueError('Playback frame is unavailable')
        frame = frames[frame_index]
        result = self._result(item, snapshot, frame_index, history)
        if 'flowDisplay' in frame:
            previous = frames[max(0, frame_index - 1)]
            validate_flow_display(frame['flowDisplay'], scene_id=result.scene.identity,
                action_index=position, frame_index=frame_index, before_state_id=previous['stateId'],
                state_id=result.state_id, start_seconds=previous['observedTimeSeconds'],
                end_seconds=frame['observedTimeSeconds'], shape=result.scene.shape)
        check()
        manifest = [{k:v for k,v in value.items() if k not in ('state', 'flowDisplay')} | {'frameIndex':i} for i,value in enumerate(frames)]
        start = frames[0]['observedTimeSeconds']
        return result, copy.deepcopy(history), {'readOnly': True, 'position': position, 'actionIndex': position,
            'frameIndex':frame_index, 'frameCount':len(frames), 'frames':manifest,
            'observedTimeSeconds':frame['observedTimeSeconds'],
            'actionElapsedSeconds':frame['observedTimeSeconds']-start,
            'actionDurationSeconds':frames[-1]['observedTimeSeconds']-start,
            'isActionBoundary':frame_index in (0,len(frames)-1), 'effectiveActivation':frame['effectiveActivation'],
            'frameStateId':result.state_id,
            **({'flowDisplay': copy.deepcopy(frame['flowDisplay'])} if 'flowDisplay' in frame else {})}
